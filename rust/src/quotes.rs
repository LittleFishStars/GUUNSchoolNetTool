/// 今天该显示的名言
pub fn today() -> &'static str {
    let day_of_year = chrono::Local::now().ordinal() as usize;
    QUOTES[(day_of_year.saturating_sub(1)) % QUOTES.len()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 每天都能取到非空名言() {
        assert!(!today().is_empty());
        // 一年 366 天都要落在有效范围内
        for day in 1..=366usize {
            assert!(!QUOTES[(day - 1) % QUOTES.len()].is_empty());
        }
    }
}
